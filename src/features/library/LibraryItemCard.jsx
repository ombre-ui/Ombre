import { FileText, Sparkles as SparklesIcon } from 'lucide-react'
import './library.css'

const KIND_LABEL = {
  note: 'Note',
  document: 'Document',
  code: 'Code',
  image: 'Image',
}

export default function LibraryItemCard({ item }) {
  return (
    <div className="library-card motion-reveal">
      <div className="library-card-top">
        <span className={`library-card-source library-card-source-${item.source}`}>
          {item.source === 'ombre' ? (
            <SparklesIcon size={12} strokeWidth={2} aria-hidden="true" />
          ) : (
            <FileText size={12} strokeWidth={2} aria-hidden="true" />
          )}
          {item.source === 'ombre' ? 'Generated by Ombre' : 'Sent by you'}
        </span>
        <span className="text-meta">{KIND_LABEL[item.kind] ?? item.kind}</span>
      </div>
      <h3 className="text-heading-sm library-card-title">{item.title}</h3>
      {item.preview && <p className="text-body-sm text-secondary library-card-preview">{item.preview}</p>}
    </div>
  )
}
