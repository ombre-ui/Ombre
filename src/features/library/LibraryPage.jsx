import { useState } from 'react'
import { useOmbreData } from '../../lib/store.jsx'
import LibraryItemCard from './LibraryItemCard.jsx'
import './library.css'

const FILTERS = [
  { id: 'all', label: 'Everything' },
  { id: 'user', label: 'Sent by You' },
  { id: 'ombre', label: 'Generated by Ombre' },
]

const EMPTY_COPY = {
  all: 'Nothing here yet. Files you send and outputs Ombre generates will both show up here.',
  user: 'Nothing sent yet. Files and notes you share with Ombre will appear here.',
  ombre: 'Nothing generated yet. Outputs Ombre creates for you will appear here.',
}

export default function LibraryPage() {
  const { listLibraryItems } = useOmbreData()
  const [filter, setFilter] = useState('all')
  const items = listLibraryItems(filter)

  return (
    <div className="library-page motion-reveal">
      <header className="library-header">
        <h1 className="text-heading-lg">Library</h1>
        <p className="text-body text-secondary">Everything you've sent, and everything Ombre has generated for you.</p>
      </header>

      <div className="library-filters" role="tablist" aria-label="Filter library">
        {FILTERS.map((f) => (
          <button
            key={f.id}
            type="button"
            role="tab"
            aria-selected={filter === f.id}
            className={`library-filter motion-interactive ${filter === f.id ? 'is-active' : ''}`}
            onClick={() => setFilter(f.id)}
          >
            {f.label}
          </button>
        ))}
      </div>

      {items.length === 0 ? (
        <div className="library-empty">
          <p className="text-body text-secondary">{EMPTY_COPY[filter]}</p>
        </div>
      ) : (
        <div className="library-grid">
          {items.map((item) => (
            <LibraryItemCard key={item.id} item={item} />
          ))}
        </div>
      )}
    </div>
  )
}
