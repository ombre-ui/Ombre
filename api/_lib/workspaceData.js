// A4 workspace data: column lists, request parsers (explicit allowlists, never pass-through) and row mappers.
// Rows are never returned as-is: every response field is named here.
import { badRequest } from './errors.js'
import { isUuid, parseUuid } from './params.js'
import { isMentorId } from '../../src/features/mentors/catalogData.js'

// ---- limits (mirrored by CHECK constraints in the migrations) ----
export const PROJECT_NAME_MAX = 100
export const PROJECT_DESCRIPTION_MAX = 2000
export const CONVERSATION_TITLE_MAX = 120
export const DERIVED_TITLE_MAX = 60
export const MESSAGE_CONTENT_MAX = 8000
export const DEFAULT_CONVERSATION_TITLE = 'Untitled conversation'
// 8000 characters x up to 4 bytes of UTF-8, plus the JSON envelope.
export const MESSAGE_BODY_MAX_BYTES = 40960
export const MESSAGES_PAGE_DEFAULT = 100
export const MESSAGES_PAGE_MAX = 100

