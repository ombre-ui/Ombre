export const PROJECT_COLUMNS = 'id,name,description,archived_at,created_at,updated_at'
// Conversation count per project, through the named composite foreign key.
export const PROJECT_LIST_SELECT = `${PROJECT_COLUMNS},conversations:conversations!conversations_project_fk(count)`
export const CONVERSATION_COLUMNS = 'id,project_id,mentor_id,title,message_count,last_message_at,created_at,updated_at'
export const MESSAGE_COLUMNS = 'id,conversation_id,seq,role,content,is_demo,created_at'
export const SAVED_COLUMNS = 'id,conversation_id,message_id,created_at'
export const LIBRARY_COLUMNS = 'id,project_id,source,kind,title,preview,created_at'

// ---- allowed JSON keys per route (anything else is a 400) ----
export const PROJECT_CREATE_KEYS = ['name', 'description']
export const PROJECT_PATCH_KEYS = ['name', 'description', 'archived']
export const CONVERSATION_CREATE_KEYS = ['content', 'clientRequestId', 'mentorId', 'projectId']
export const CONVERSATION_PATCH_KEYS = ['title', 'projectId']
export const MESSAGE_CREATE_KEYS = ['role', 'content', 'clientRequestId']
export const SAVED_CREATE_KEYS = ['conversationId', 'messageId']

// Control characters (C0/C1, line and paragraph separators). Names and titles are single lines.
const CONTROL_CHARS_RE = /[\u0000-\u001F\u007F-\u009F\u2028\u2029]/
// Multi-line text may keep tab, LF and CR; everything else in the control ranges is rejected.
const MULTILINE_FORBIDDEN_RE = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F-\u009F\u2028\u2029]/

const has = (obj, key) => Object.prototype.hasOwnProperty.call(obj, key)
const codePoints = (s) => Array.from(s).length

function singleLine(value, max) {
  if (typeof value !== 'string' || !value.isWellFormed()) throw badRequest()
  const text = value.normalize('NFC').trim()
  if (text === '' || CONTROL_CHARS_RE.test(text) || codePoints(text) > max) throw badRequest()
  return text
}

export function parseProjectName(value) {
  return singleLine(value, PROJECT_NAME_MAX)
}

export function parseProjectDescription(value) {
  if (typeof value !== 'string' || !value.isWellFormed()) throw badRequest()
  const text = value.normalize('NFC').trim()
  if (MULTILINE_FORBIDDEN_RE.test(text) || codePoints(text) > PROJECT_DESCRIPTION_MAX) throw badRequest()
  return text
}

export function parseConversationTitle(value) {
  return singleLine(value, CONVERSATION_TITLE_MAX)
}

// Message content is stored exactly as sent (not trimmed or normalised). It must be non-blank, well-formed
// UTF-16 (a lone surrogate cannot be stored as UTF-8), contain no NUL (Postgres text cannot), and be at most
// 8000 characters (code points, as char_length counts).
export function parseMessageContent(value) {
  if (typeof value !== 'string' || !value.isWellFormed()) throw badRequest()
  if (value.includes('\u0000') || value.trim() === '' || codePoints(value) > MESSAGE_CONTENT_MAX) throw badRequest()
  return value
}

export function parseMessageRole(value) {
  if (value === 'user' || value === 'assistant') return value
  throw badRequest()
}

// Required on every message-creating request: it makes retries idempotent. It is an idempotency key, not a row
// id (row ids are always generated by the database).
export function parseClientRequestId(value) {
  return parseUuid(value)
}

export function parseOptionalMentorId(value) {
  if (value === undefined || value === null) return null
  if (!isMentorId(value)) throw badRequest()
  return value
}

export function parseOptionalProjectId(value) {
  if (value === undefined || value === null) return null
  return parseUuid(value)
}

// Title for a new conversation: the first message collapsed to one line, 60 characters (as the demo store did).
export function deriveTitle(content) {
  const oneLine = content.replace(/\s+/g, ' ').trim()
  const title = Array.from(oneLine).slice(0, DERIVED_TITLE_MAX).join('').trim()
  return title === '' ? DEFAULT_CONVERSATION_TITLE : title
}

// ---- request parsers: return only column-allowlisted rows ----

export function parseProjectCreate(body) {
  if (!has(body, 'name')) throw badRequest()
  return {
    name: parseProjectName(body.name),
    description: has(body, 'description') ? parseProjectDescription(body.description) : '',
  }
}

export function parseProjectPatch(body) {
  const row = {}
  if (has(body, 'name')) row.name = parseProjectName(body.name)
  if (has(body, 'description')) row.description = parseProjectDescription(body.description)
  if (has(body, 'archived')) {
    if (typeof body.archived !== 'boolean') throw badRequest()
    row.archived_at = body.archived ? new Date().toISOString() : null // clients never send timestamps
  }
  if (Object.keys(row).length === 0) throw badRequest()
  return row
}

export function parseConversationPatch(body) {
  const row = {}
  if (has(body, 'title')) row.title = parseConversationTitle(body.title)
  if (has(body, 'projectId')) row.project_id = body.projectId === null ? null : parseUuid(body.projectId)
  if (Object.keys(row).length === 0) throw badRequest()
  return row
}

export function parseConversationCreate(body) {
  if (!has(body, 'content') || !has(body, 'clientRequestId')) throw badRequest()
  const content = parseMessageContent(body.content)
  return {
    content,
    clientRequestId: parseClientRequestId(body.clientRequestId),
    mentorId: parseOptionalMentorId(body.mentorId),
    projectId: parseOptionalProjectId(body.projectId),
    title: deriveTitle(content),
  }
}

// The browser-facing path only ever creates (user, not demo) or (assistant, demo) messages. isDemo is derived
// from the role here and is never read from the request; the database policy enforces the same pairs.
export function parseMessageCreate(body) {
  if (!has(body, 'role') || !has(body, 'content') || !has(body, 'clientRequestId')) throw badRequest()
  const role = parseMessageRole(body.role)
  return {
    role,
    content: parseMessageContent(body.content),
    clientRequestId: parseClientRequestId(body.clientRequestId),
    isDemo: role === 'assistant',
  }
}

export function parseSavedCreate(body) {
  if (!has(body, 'conversationId')) throw badRequest()
  const messageId = has(body, 'messageId') && body.messageId !== null ? parseUuid(body.messageId) : null
  return { conversationId: parseUuid(body.conversationId), messageId }
}

// ---- row mappers: snake_case rows -> the camelCase wire shapes documented in docs/workspace-data.md ----

export function rowToProject(row) {
  const out = {
    id: row.id,
    name: row.name,
    description: row.description,
    archivedAt: row.archived_at,
    createdAt: row.created_at,
    updatedAt: row.updated_at,
  }
  if (Array.isArray(row.conversations) && row.conversations[0] && typeof row.conversations[0].count === 'number') {
    out.conversationCount = row.conversations[0].count
  }
  return out
}

export function rowToConversation(row) {
  return {
    id: row.id,
    title: row.title,
    projectId: row.project_id,
    mentorId: row.mentor_id,
    messageCount: row.message_count,
    lastMessageAt: row.last_message_at,
    createdAt: row.created_at,
    updatedAt: row.updated_at,
  }
}

// Matches the frontend Message shape. Persisted messages are always terminal ('complete'); pending and error
// states exist only in the client. Attachments do not exist in A4.
export function rowToMessage(row) {
  return {
    id: row.id,
    conversationId: row.conversation_id,
    seq: row.seq,
    role: row.role,
    content: row.content,
    status: 'complete',
    demo: row.is_demo === true,
    attachments: [],
    createdAt: row.created_at,
  }
}

export function rowToSaved(row) {
  return { id: row.id, conversationId: row.conversation_id, messageId: row.message_id, createdAt: row.created_at }
}

export function rowToLibraryItem(row) {
  return {
    id: row.id,
    title: row.title,
    source: row.source,
    kind: row.kind,
    preview: row.preview,
    projectId: row.project_id,
    createdAt: row.created_at,
  }
}

